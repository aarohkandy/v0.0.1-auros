// Bundles AurOS's help pages (rootfs/usr/share/auros/help/*.html) into
// src/help.gen.js as plain text, so "Ask AurOS" is grounded in exactly the
// pages the computer shows. Run by `npm test` and by wrangler before a deploy.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../rootfs/usr/share/auros/help/", import.meta.url);
const ENT = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", nbsp: " ", rsquo: "’", lsquo: "‘", rdquo: "”", ldquo: "“", larr: "←", rarr: "→", mdash: "—", ndash: "–", hellip: "…", times: "×" };
const text = (html) => html
  .replace(/<(script|style|header|nav|footer)\b[\s\S]*?<\/\1>/gi, "")
  .replace(/<h1[^>]*>/gi, "\n# ").replace(/<h2[^>]*>/gi, "\n## ").replace(/<h3[^>]*>/gi, "\n### ")
  .replace(/<li[^>]*>/gi, "\n- ").replace(/<(p|br|div|ol|ul|tr)\b[^>]*>/gi, "\n")
  .replace(/<[^>]+>/g, "")
  .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(+n))
  .replace(/&([a-z]+);/gi, (m, n) => ENT[n.toLowerCase()] ?? m)
  .replace(/[ \t]+/g, " ").replace(/ *\n */g, "\n").replace(/\n{3,}/g, "\n\n").trim();

const pages = readdirSync(dir).filter((f) => f.endsWith(".html")).sort().map((f) => {
  const html = readFileSync(new URL(f, dir), "utf8");
  return { id: f.replace(/\.html$/, ""), title: (html.match(/<title>([^<]*)<\/title>/i)?.[1] ?? f).replace(/\s*-\s*AurOS help$/, ""), text: text(html.match(/<main[\s\S]*<\/main>/i)?.[0] ?? html) };
});
if (pages.length === 0) throw new Error("no help pages found in " + dir.pathname);
writeFileSync(new URL("./src/help.gen.js", import.meta.url),
  `// Generated by build-help.mjs from rootfs/usr/share/auros/help/. Do not edit.\nexport default ${JSON.stringify(pages, null, 1)};\n`);
console.log(`help pages: ${pages.map((p) => p.id).join(", ")}`);
