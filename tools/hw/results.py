#!/usr/bin/env python3
"""results.py -- docs/results/hardware/<machine>.txt  ->  README.md table.

  python3 -I tools/hw/results.py [--dir DIR] [--out FILE] [--check]

One file per physical PC, written by the owner from CAMPAIGN.md's sheet
(or by an agent from his photographs): `key: value` lines, then `---`,
then free notes. `<machine>.report.json` next to it is the AurOS-report.json
that PC produced. The table says, for every machine, what the report
PREDICTED for Wi-Fi, sound, camera, printer, and what really happened, and
counts the two misses that matter: promised and failed ("works" but did
not), refused wrongly ("won't work" but did). WP-33: the share of PCs the
installer refused, and why, is the first thing the README says.

--check: only validate the files (exit 1 on a bad value). No file: fine.
"""
import argparse, glob, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))

ENUM = {
    "install": {"ok", "refused", "failed", "not-tried"},
    "put_windows_back": {"ok", "failed", "not-tried"},
    "power_pull": {"ok", "failed", "not-tried"},
    "data_loss": {"no", "yes"},
    "screen_ok": {"yes", "slow", "no"},
}
OBSERVED = ["wifi", "sound", "camera", "bluetooth", "printer", "scanner", "fingerprint"]
YN = {"yes", "no", "n/a", "untested"}
# the report's verdict kind for each thing the owner checks
KIND = {"wifi": "wifi", "sound": "audio", "camera": "camera", "bluetooth": "bluetooth",
        "scanner": "scanner", "fingerprint": "fingerprint"}
REQUIRED = ["machine", "date", "install", "put_windows_back", "data_loss"]


def parse(path):
    d, notes, in_notes = {}, [], False
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        if in_notes:
            notes.append(line)
        elif line.strip() == "---":
            in_notes = True
        elif ":" in line and not line.lstrip().startswith("#"):
            k, v = line.split(":", 1)
            d[k.strip()] = v.strip()
    d["_notes"] = "\n".join(notes).strip()
    d["_file"] = os.path.basename(path)
    return d


def validate(d):
    errs = []
    for k in REQUIRED:
        if not d.get(k):
            errs.append("%s: missing '%s'" % (d["_file"], k))
    for k, ok in ENUM.items():
        if d.get(k) and d[k] not in ok:
            errs.append("%s: %s is '%s' (one of %s)" % (d["_file"], k, d[k], "/".join(sorted(ok))))
    for k in OBSERVED:
        v = d.get(k + "_worked")
        if v and v not in YN:
            errs.append("%s: %s_worked is '%s' (one of %s)" % (d["_file"], k, v, "/".join(sorted(YN))))
    if d.get("minutes_to_yes") and not d["minutes_to_yes"].isdigit():
        errs.append("%s: minutes_to_yes must be a number" % d["_file"])
    if d.get("install") == "refused" and not d.get("refused_because"):
        errs.append("%s: install is 'refused': say why in refused_because" % d["_file"])
    return errs


def predicted(rep):
    out = {}
    for v in rep.get("verdicts", []):
        if v.get("printer", -1) >= 0:
            out["printer"] = worst(out.get("printer"), v["state"])
        else:
            k = [a for a, b in KIND.items() if b == v["kind"]]
            if k:
                out[k[0]] = v["state"]
    return out


def worst(a, b):
    order = ["works", "partial", "unknown", "wont"]
    return b if a is None or order.index(b) > order.index(a) else a


def judge(pred, obs):
    """hit / miss-promised / miss-refused / '' (not a prediction or not tried)"""
    if obs not in ("yes", "no") or pred in (None, "partial", "unknown", "none"):
        return ""
    if pred == "works":
        return "hit" if obs == "yes" else "PROMISED, FAILED"
    return "hit" if obs == "no" else "REFUSED WRONGLY"


def load(dirp):
    rows = []
    for p in sorted(glob.glob(os.path.join(dirp, "*.txt"))):
        if os.path.basename(p) in ("TEMPLATE.txt", "SAMPLE-REPORT.txt"):
            continue
        d = parse(p)
        rp = p[:-4] + ".report.json"
        d["_report"] = json.load(open(rp, encoding="utf-8")) if os.path.exists(rp) else None
        rows.append(d)
    return rows


def render(rows):
    o = ["# Real-PC results (generated by tools/hw/results.py: edit the .txt files, not this table)", ""]
    n = len(rows)
    if not n:
        o += ["No machine yet. `CAMPAIGN.md` says which five to buy and what to do with each.", ""]
        return "\n".join(o) + "\n"
    refused = [r for r in rows if r.get("install") == "refused"]
    ok = [r for r in rows if r.get("install") == "ok"]
    o += ["%d machine%s. Installed and kept working: %d. Refused by the installer: %d%s. Data lost on any: %d." % (
        n, "" if n == 1 else "s", len(ok), len(refused),
        (" (" + "; ".join("%s: %s" % (r["machine"], r.get("refused_because", "?")) for r in refused) + ")") if refused else "",
        sum(1 for r in rows if r.get("data_loss") == "yes")), ""]
    misses, hits = [], 0
    o += ["| Machine | Windows | Disk | BitLocker | Install | Minutes | Put Windows back | Wi-Fi (said / was) | Sound | Camera | Printer |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        rep, pred = r["_report"] or {}, {}
        if rep:
            pred = predicted(rep)
        sd, win = rep.get("system_drive", {}), rep.get("windows", {})
        cells = []
        for k in ("wifi", "sound", "camera", "printer"):
            obs = r.get(k + "_worked", "")
            j = judge(pred.get(k), obs)
            if j == "hit":
                hits += 1
            elif j:
                misses.append((r["machine"], k, pred.get(k), obs, j))
            cells.append("%s / %s%s" % (pred.get(k, "-"), obs or "-", " **%s**" % j if j and j != "hit" else ""))
        disk = ("SSD" if sd.get("kind") == 1 else "HDD" if sd.get("kind") == 0 else "?") if sd else "?"
        o.append("| %s | %s | %s | %s | %s | %s | %s | %s |" % (
            r["machine"], ("%s %s" % (win.get("name", ""), win.get("display", ""))).strip() or "?", disk,
            {1: "yes", 0: "no"}.get(sd.get("bitlocker"), "?") if sd else "?",
            r.get("install", "?"), r.get("minutes_to_yes", "-"), r.get("put_windows_back", "?"), " | ".join(cells)))
    o += ["", "Predictions that could be checked: %d hit, %d wrong." % (hits, len(misses)), ""]
    if misses:
        o += ["## Wrong predictions (these are the ones to fix first)", ""]
        for m in misses:
            o.append("- **%s**, %s: the report said `%s`, the real result was `%s`: %s" % m)
        o.append("")
    return "\n".join(o) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=os.path.join(REPO, "docs", "results", "hardware"))
    ap.add_argument("--out")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    rows = load(a.dir)
    errs = [e for r in rows for e in validate(r)]
    for e in errs:
        print("results:", e, file=sys.stderr)
    if errs:
        return 1
    if a.check:
        return 0
    out = a.out or os.path.join(a.dir, "README.md")
    open(out, "w", encoding="utf-8").write(render(rows))
    return 0


if __name__ == "__main__":
    sys.exit(main())
