#!/usr/bin/env python3
"""gen-header.py -- hw/compat.json -> the two C headers the matcher compiles.

  python3 -I tools/hw/gen-header.py OUTDIR

  OUTDIR/hwcompat_data.h    tables: which module claims which PCI/USB id,
                            the rules, the printer models. Includes 'why'
                            text (ours, may be technical).
  OUTDIR/hwcompat_words.h   ONLY the sentences she reads, one #define each
                            (W_wifi_works ...). tools/wordlint.sh lints
                            this file, so a forbidden word fails CI.

Not committed: build/aurbridge and tools/hw/hwtest.sh make them from the
committed hw/compat.json (250 KB of readable JSON) into a scratch
directory. The build needs Python (it already does, for the manifest) and
no image.
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
CATN = {"wifi": 1, "ethernet": 2, "bluetooth": 3, "audio": 4, "camera": 5, "gpu": 6, "bus": 7}
KINDN = {"wifi": 1, "ethernet": 2, "bluetooth": 3, "audio": 4, "camera": 5, "gpu": 6, "storage": 7,
         "scanner": 8, "fingerprint": 9, "printer": 10}
STATEN = {"works": 0, "partial": 1, "wont": 2, "unknown": 3, "none": 4}
BUSN = {"pci": 1, "usb": 2, "hda": 3, "acpi": 4}


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def hx(x):
    return 0xFFFF if x == "*" else int(x, 16)


def cls(c):
    """'040300' / '04****' -> (value, mask) of 24 bits"""
    if not c:
        return 0, 0
    val = mask = 0
    for i in range(0, 6, 2):
        part = c[i:i + 2]
        val <<= 8
        mask <<= 8
        if part != "**":
            val |= int(part, 16)
            mask |= 0xFF
    return val, mask


def entry(bus, s, mod):
    cc = ""
    if "@" in s:
        s, cc = s.split("@", 1)
    sub = ""
    if "/" in s:
        s, sub = s.split("/", 1)
    v, d = s.split(":")
    sv, sd = ("*", "*") if not sub else sub.split(":")
    val, mask = cls(cc.ljust(6, "*") if cc else "")
    return "{0x%04X,0x%04X,0x%04X,0x%04X,0x%06X,0x%06X,%d,%d}" % (
        hx(v), hx(d), hx(sv), hx(sd), val, mask, mod, bus)


def build(c):
    feats = c["image"]["features"]
    mods = sorted(c["modules"])
    idx = {m: i for i, m in enumerate(mods)}
    o = []
    w = o.append
    w("/* GENERATED by tools/hw/gen-header.py from hw/compat.json. Do not edit. */")
    w("#ifndef HWCOMPAT_DATA_H\n#define HWCOMPAT_DATA_H\n#include <stdint.h>\n")
    w("#define HWC_KERNEL %s" % cstr(c["image"]["kernel"]))
    for k in sorted(feats):
        w("#define HWC_F_%s %d" % (k, 1 if feats[k] else 0))
    w("\ntypedef struct { uint16_t vid, did, svid, sdid; uint32_t cc, ccmask; uint16_t mod; uint8_t bus; } hwc_alias;")
    w("typedef struct { const char *name; uint8_t cat, fw_unusable; } hwc_module;")
    w("/* cat: 1 wifi 2 ethernet 3 bluetooth 4 audio 5 camera 6 gpu 7 bus-only (bcma, ssb: a door, not a driver) */")
    w("/* fw_unusable: the driver cannot start, because firmware it must have is not in the image */")
    w("static const hwc_module hwc_modules[] = {")
    for m in mods:
        e = c["modules"][m]
        w('  {%s,%d,%d},' % (cstr(m), CATN[e["cat"]], 1 if (e["fw_required"] and e["fw"] == "missing") else 0))
    w("};\n#define HWC_N_MODULES %d\n" % len(mods))
    rows = []
    for m in mods:
        e = c["modules"][m]
        for s in e.get("pci", "").split():
            rows.append(entry(1, s, idx[m]))
        for s in e.get("usb", "").split():
            rows.append(entry(2, s, idx[m]))
    w("static const hwc_alias hwc_aliases[] = {")
    for i in range(0, len(rows), 3):
        w("  " + ",".join(rows[i:i + 3]) + ",")
    w("};\n#define HWC_N_ALIASES %d\n" % len(rows))

    # rules
    act = [r for r in c["rules"] if not (r.get("unless_feature") and feats.get(r["unless_feature"]))]
    w("typedef struct {")
    w("  const char *id; uint8_t verdict, state, bus, need, any_kind; uint16_t vid;")
    w("  const uint16_t *did; int ndid; const char *const *names; int nnames;")
    w("  const char *says; const char *why;")
    w("} hwc_rule;")
    w("/* need: 0 always, 1 only if no driver claims the device, 2 only if one does */")
    for i, r in enumerate(act):
        if r.get("did"):
            w("static const uint16_t hwc_r%d_did[] = {%s};" % (i, ",".join("0x%04X" % int(x, 16) for x in r["did"])))
        if r.get("name_has"):
            w("static const char *const hwc_r%d_names[] = {%s};" % (i, ",".join(cstr(x) for x in r["name_has"])))
    w("static const hwc_rule hwc_rules[] = {")
    for i, r in enumerate(act):
        w("  {%s,%d,%d,%d,%d,%d,0x%04X,%s,%d,%s,%d,%s,%s}," % (
            cstr(r["id"]), KINDN[r["verdict"]], STATEN[r["state"]], BUSN.get(r.get("bus", ""), 0),
            {"nodriver": 1, "driver": 2}.get(r.get("need", ""), 0), 1 if r.get("any_kind") else 0,
            int(r["vid"], 16) if r.get("vid") else 0,
            ("hwc_r%d_did" % i) if r.get("did") else "0", len(r.get("did", [])),
            ("hwc_r%d_names" % i) if r.get("name_has") else "0", len(r.get("name_has", [])),
            cstr(c["words"][r["says"]]), cstr(r["why"])))
    w("};\n#define HWC_N_RULES %d\n" % len(act))

    models = c["printers"]["models"]
    w("/* what CUPS can drive without being told: HP (hpcups) and Gutenprint, lower case, words split on anything not a letter or digit */")
    w("static const char *const hwc_printer_models[] = {")
    for i in range(0, len(models), 4):
        w("  " + ",".join(cstr(x) for x in models[i:i + 4]) + ",")
    w("};\n#define HWC_N_PRINTER_MODELS %d\n#endif" % len(models))
    data = "\n".join(o) + "\n"

    ws = ["/* GENERATED by tools/hw/gen-header.py from hw/seeds.json. Do not edit.",
          " * Only what she reads: tools/wordlint.sh lints this file. */",
          "#ifndef HWCOMPAT_WORDS_H\n#define HWCOMPAT_WORDS_H"]
    for k in sorted(c["words"]):
        ws.append("#define W_%s %s" % (re.sub(r"[^A-Za-z0-9]", "_", k), cstr(c["words"][k])))
    ws.append("#endif")
    return data, "\n".join(ws) + "\n"


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: gen-header.py OUTDIR")
    outdir = sys.argv[1]
    c = json.load(open(os.path.join(REPO, "hw", "compat.json"), encoding="utf-8"))
    data, words = build(c)
    os.makedirs(outdir, exist_ok=True)
    for name, t in (("hwcompat_data.h", data), ("hwcompat_words.h", words)):
        with open(os.path.join(outdir, name), "w", encoding="utf-8") as f:
            f.write(t)
    return 0


if __name__ == "__main__":
    sys.exit(main())
