#!/usr/bin/env python3
"""Compile one raw recipe into the inert C data baked into AurBridge."""

from __future__ import annotations

import argparse
import json
import os
import sys
import tempfile
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from src.customize.recipe import (  # noqa: E402
    MAX_RECIPE_BYTES,
    RecipeError,
    compile_recipe,
    parse_recipe,
)


# A profile belongs here only after its image and its profile-specific journey
# have passed the public delivery gates. Recipe validation supports all five
# reusable bases; packaging is deliberately stricter than validation.
DELIVERABLE_BASES = frozenset({"desktop"})


class InstallerRecipeError(ValueError):
    pass


def compile_installer_recipe(raw: bytes, image_profile: str) -> str:
    """Return a complete generated header for a matching, deliverable image."""

    plan = compile_recipe(parse_recipe(raw))
    base = plan["base_profile"]
    if base != image_profile:
        raise InstallerRecipeError(
            f"recipe base {base!r} does not match trusted image profile {image_profile!r}"
        )
    if base not in DELIVERABLE_BASES:
        raise InstallerRecipeError(
            f"profile {base!r} is not enabled for personalized installer delivery"
        )

    resolved = plan["resolved_preferences"]
    values = {
        "AUROS_RECIPE_BASE": base,
        "AUROS_RECIPE_LOOK": resolved["look"],
        "AUROS_RECIPE_THEME": resolved["theme"],
        "AUROS_RECIPE_ID": plan["recipe_id"],
    }
    lines = [
        "/* generated by tools/customize/installer_recipe.py; do not edit */",
        "#ifndef AUROS_INSTALLER_RECIPE_GENERATED_H",
        "#define AUROS_INSTALLER_RECIPE_GENERATED_H",
        "#define AUROS_RECIPE_PRESENT 1",
    ]
    for name, value in values.items():
        # json.dumps supplies a valid C string for these validated ASCII enums
        # and the lowercase sha256 identity. Nothing is interpreted as code.
        lines.append(f"#define {name} {json.dumps(value, ensure_ascii=True)}")
    lines.extend(("#endif", ""))
    return "\n".join(lines)


def _read_limited(path: Path) -> bytes:
    try:
        with path.open("rb") as stream:
            data = stream.read(MAX_RECIPE_BYTES + 1)
    except OSError as exc:
        raise InstallerRecipeError(f"could not read recipe: {exc}") from exc
    if len(data) > MAX_RECIPE_BYTES:
        raise InstallerRecipeError(f"recipe exceeds the {MAX_RECIPE_BYTES}-byte limit")
    return data


def _write_atomic(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary: str | None = None
    try:
        fd, temporary = tempfile.mkstemp(prefix=path.name + ".", dir=path.parent)
        with os.fdopen(fd, "w", encoding="ascii", newline="\n") as stream:
            stream.write(text)
        os.replace(temporary, path)
    except OSError as exc:
        if temporary is not None:
            try:
                os.unlink(temporary)
            except OSError:
                pass
        raise InstallerRecipeError(f"could not write generated header: {exc}") from exc


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("recipe", type=Path, help="raw recipe v1 JSON")
    parser.add_argument("--image-profile", required=True, help="trusted built image profile")
    parser.add_argument("--output", required=True, type=Path, help="generated C header")
    args = parser.parse_args(argv)

    try:
        # A failed repeat build must not leave yesterday's valid recipe in the
        # output directory for the compiler to discover with __has_include.
        try:
            args.output.unlink()
        except FileNotFoundError:
            pass
        except OSError as exc:
            raise InstallerRecipeError(
                f"could not remove stale generated header: {exc}"
            ) from exc
        header = compile_installer_recipe(_read_limited(args.recipe), args.image_profile)
        _write_atomic(args.output, header)
    except (RecipeError, InstallerRecipeError) as exc:
        print(f"installer recipe: {exc}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
