#!/usr/bin/env node
// Keep the static website's natural-language interpreter byte-for-byte derived
// from cloud/src/configure.js. The only transformation replaces Node's JSON
// import with the same checked-in schema embedded as browser JavaScript.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const sourcePath = path.join(repo, "cloud", "src", "configure.js");
const schemaPath = path.join(repo, "src", "customize", "recipe-v1.schema.json");
const outputPath = path.join(repo, "website", "assets", "configure-generated.js");
const importLine = 'import recipeSchema from "../../src/customize/recipe-v1.schema.json" with { type: "json" };';

const source = fs.readFileSync(sourcePath, "utf8");
if (!source.includes(importLine)) {
  throw new Error(`configure browser generator: expected schema import not found in ${sourcePath}`);
}
const schema = JSON.parse(fs.readFileSync(schemaPath, "utf8"));
const replacement = `const recipeSchema = Object.freeze(${JSON.stringify(schema)});`;
const generated = `// GENERATED by tools/site/generate-configure-browser.mjs. Do not edit.\n${source.replace(importLine, replacement)}`;

if (process.argv.includes("--check")) {
  let current = "";
  try { current = fs.readFileSync(outputPath, "utf8"); } catch {}
  if (current !== generated) {
    console.error("configure browser generator: website/assets/configure-generated.js is stale");
    process.exit(1);
  }
} else {
  fs.writeFileSync(outputPath, generated);
}
